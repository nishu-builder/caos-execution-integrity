const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1200,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const base=process.env.MYSTERY_URL||'http://127.0.0.1:18184/mystery.html';
await page.goto(base);
await page.waitForFunction(()=>document.querySelector('#events article'));
const publicCount=await page.locator('#events article').count();
assert(publicCount>0);
assert.equal(await page.locator('#chat option').count(),1);
await page.check('#private');
await page.selectOption('#chat','*');
const all=await page.locator('#events article').count();
assert(all>publicCount);
await page.selectOption('#recipient','iris');
assert((await page.locator('#events article').count())<all);
const captured=await page.evaluate(()=>fetch('mystery/state.json').then(r=>r.json()));
assert.equal(await page.locator('#events article').count(),captured.events.filter(e=>e.visible_to.includes('iris')).length);
await page.uncheck('#private');
assert.equal(await page.locator('#events article').count(),publicCount);
await page.locator('summary').first().click();
const link=await page.locator('#cast a').first().getAttribute('href');
const url=new URL(link);assert.equal(url.pathname,'/trajectories/');assert(url.searchParams.get('head').length===40);assert.equal(url.searchParams.get('remote'),new URL('mystery/git',base).href);
await page.evaluate(()=>window.scrollTo(0,0));
if(process.env.MYSTERY_SCREENSHOT) await page.screenshot({path:process.env.MYSTERY_SCREENSHOT,fullPage:false});
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
assert.deepEqual(errors,[]);
await page.goto(link);
await page.waitForSelector('#browser:not([hidden])',{timeout:60000});
assert.match(await page.locator('#detail').innerText(),/notes|actions/);
await page.waitForTimeout(1000);
assert(!await page.locator('body').innerText().then(t=>/Failed to load|Hash mismatch|Could not load/.test(t)));
console.log(JSON.stringify({publicMessages:publicCount,allEvents:all,sourceLink:link,errors}));
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
